// >	Greater Than
// <	Less Than
// >=	Greater Than Equal
// <=	Less Than Equal
// ==	Equal To
// !=	Not Equal To

public class P07_Relation_Operator {
    public static void main(String[] agrs){
        int a = 10;
        int b = 20;

        System.out.println("a > b: " + (a > b)); // false
        System.out.println("a < b: " + (a < b)); // true
        System.out.println("a >= b: " + (a >= b)); // false
        System.out.println("a <= b: " + (a <= b)); // true
        System.out.println("a == b: " + (a == b)); // false
        System.out.println("a != b: " + (a != b)); // true
    }
}
